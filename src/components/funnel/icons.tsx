/**
 * Icons traced out of the funnel and result exports.
 *
 * Every one is lifted from the design file's own paths rather than an icon package,
 * so weights and corner radii match what was drawn.
 *
 * Each renders at the size it was drawn at, and those sizes genuinely differ - the
 * eye is 22×15, the shield 16×20. Sizing them all to one width (or one height) is
 * what makes a row of them look wrong: forcing the 16×20 shield to 22 wide renders
 * it 27.5 tall, overhanging the 18px label beside it. Callers that need a tidy
 * column give the icon a fixed-width *box* to sit in rather than resizing it.
 *
 * All inherit `currentColor`.
 */

type IconProps = { className?: string };

function Glyph({
  className,
  viewBox,
  width,
  height,
  d,
  evenOdd,
}: IconProps & {
  viewBox: string;
  width: number;
  height: number;
  d: string;
  /** For a glyph drawn as an outline: the ring is one contour inside another, and
   *  the default nonzero rule would flood the gap between them. */
  evenOdd?: boolean;
}) {
  return (
    <svg
      viewBox={viewBox}
      width={width}
      height={height}
      fill="currentColor"
      aria-hidden
      className={className}
    >
      <path d={d} fillRule={evenOdd ? "evenodd" : undefined} />
    </svg>
  );
}

